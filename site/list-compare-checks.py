class _NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        return None


def run_public():
    local_path = page_path()
    with open(local_path, "rb") as fh:
        local_bytes = fh.read()
    local_sha = hashlib.sha256(local_bytes).hexdigest()

    req = urllib.request.Request(
        PUBLIC_URL,
        headers={"User-Agent": "list-compare-checks/1.0 (public body verification; single GET)"},
    )
    opener = urllib.request.build_opener(_NoRedirect)
    status = None
    remote_bytes = None
    error_text = None
    try:
        resp = opener.open(req, timeout=30)
        try:
            status = resp.getcode()
            remote_bytes = resp.read()
        finally:
            resp.close()
    except urllib.error.HTTPError as exc:
        status = exc.code
        error_text = "HTTPError %s %s" % (exc.code, exc.reason)
    except Exception as exc:  # network failure, timeout, redirect refusal
        error_text = "%s: %s" % (type(exc).__name__, exc)

    print("URL: %s" % PUBLIC_URL)
    print("HTTP status: %s" % (status if status is not None else "none (request failed)"))
    if error_text:
        print("fetch error: %s" % error_text)

    if remote_bytes is None:
        print("local bytes: %d" % len(local_bytes))
        print("local sha256: %s" % local_sha)
        print("remote bytes: n/a")
        print("remote sha256: n/a")
        print("byte_equal: false")
        print("local_body_contained: false")
        print("release marker '%s' present in remote body: false" % RELEASE_MARKER)
        print("PUBLIC FETCH-FAILED")
        return 1

    remote_sha = hashlib.sha256(remote_bytes).hexdigest()
    byte_equal = local_bytes == remote_bytes
    contained = local_bytes in remote_bytes
    marker = RELEASE_MARKER.encode("ascii") in remote_bytes
    print("local bytes: %d" % len(local_bytes))
    print("local sha256: %s" % local_sha)
    print("remote bytes: %d" % len(remote_bytes))
    print("remote sha256: %s" % remote_sha)
    print("byte_equal: %s" % ("true" if byte_equal else "false"))
    print("local_body_contained: %s" % ("true" if contained else "false"))
    print("release marker '%s' present in remote body: %s" % (RELEASE_MARKER, "true" if marker else "false"))
    ok = status == 200 and contained and marker
    print("PUBLIC %s" % ("PASS" if ok else "FAIL"))
    return 0 if ok else 1


# --------------------------------------------------------------------------

def main(argv):
    modes = [a for a in argv[1:] if a.startswith("--")]
    if len(modes) != 1 or modes[0] not in ("--core", "--static", "--public", "--all"):
        print("usage: python3 -B list-compare-checks.py --core|--static|--public|--all")
        return 2
    mode = modes[0]
    if mode == "--public":
        return run_public()

    with open(page_path(), "rb") as fh:
        html_text = fh.read().decode("utf-8")
    if mode == "--core":
        return run_core(html_text)
    if mode == "--static":
        return run_static(html_text)
    rc = run_core(html_text)
    rc2 = run_static(html_text)
    return rc if rc != 0 else rc2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
