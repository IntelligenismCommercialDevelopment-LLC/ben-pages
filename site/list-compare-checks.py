class BrowserPage(object):
    def __init__(self, objc, html_text, clipboard_mode="ok"):
        self.o = objc
        o = objc
        wv_class = o.cls("WebView")
        alloc = o.send(ctypes.c_void_p, wv_class, "alloc")
        if not alloc:
            raise BrowserUnavailable("BROWSER UNAVAILABLE: WebView alloc returned nil")
        self.wv = o.send(ctypes.c_void_p, alloc, "initWithFrame:frameName:groupName:",
                         NSRect(0, 0, 1024, 768), None, None,
                         argtypes=[NSRect, ctypes.c_void_p, ctypes.c_void_p])
        if not self.wv:
            raise BrowserUnavailable("BROWSER UNAVAILABLE: WebView init returned nil")
        self.wv = ctypes.c_void_p(self.wv)
        main_frame = o.send(ctypes.c_void_p, self.wv, "mainFrame")
        if not main_frame:
            raise BrowserUnavailable("BROWSER UNAVAILABLE: WebView has no mainFrame")
        self.main_frame = ctypes.c_void_p(main_frame)
        injected = INJECTED_DRIVER.replace("MODE", clipboard_mode)
        html = html_text.replace("</head>", injected + "\n</head>", 1)
        ns_html = self._nsstring(html)
        o.send(None, self.main_frame, "loadHTMLString:baseURL:", ns_html, None,
               argtypes=[ctypes.c_void_p, ctypes.c_void_p])
        self._pump_until_ready()

    def _nsstring(self, text):
        o = self.o
        ns = o.send(ctypes.c_void_p, o.cls("NSString"), "stringWithUTF8String:",
                    text.encode("utf-8"), argtypes=[ctypes.c_char_p])
        if not ns:
            raise BrowserUnavailable("BROWSER UNAVAILABLE: NSString creation failed")
        return ctypes.c_void_p(ns)

    def _pump(self, seconds):
        o = self.o
        rl = o.send(ctypes.c_void_p, o.cls("NSRunLoop"), "currentRunLoop")
        rl = ctypes.c_void_p(rl)
        until = o.send(ctypes.c_void_p, o.cls("NSDate"), "dateWithTimeIntervalSinceNow:",
                       ctypes.c_double(seconds), argtypes=[ctypes.c_double])
        until = ctypes.c_void_p(until)
        o.send(None, rl, "runUntilDate:", until, argtypes=[ctypes.c_void_p])

    def _pump_until_ready(self):
        ready = False
        for _ in range(120):
            self._pump(0.05)
            res = self.js("document.readyState === 'complete' && !!document.getElementById('app-root') ? 'ready' : 'wait'")
            if res == "ready":
                ready = True
                break
        if not ready:
            raise BrowserUnavailable("BROWSER UNAVAILABLE: page never reached ready state")
        self._pump(0.15)

    def js(self, code):
        o = self.o
        ns = self._nsstring(code)
        res = o.send(ctypes.c_void_p, self.wv, "stringByEvaluatingJavaScriptFromString:", ns,
                     argtypes=[ctypes.c_void_p])
        if not res:
            return None
        res = ctypes.c_void_p(res)
        utf8 = o.send(ctypes.c_void_p, res, "UTF8String")
        if not utf8:
            return ""
        return ctypes.cast(utf8, ctypes.c_char_p).value.decode("utf-8", "replace")

    def close(self):
        try:
            self.o.send(None, self.wv, "release", argtypes=[])
        except Exception:
            pass


