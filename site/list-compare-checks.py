#!/usr/bin/env python3
"""list-compare-checks.py - independent re-check tool for the list-compare page.

This program is read-only: every mode writes only to stdout / stderr. It never
writes report files, caches, downloaded bodies or temporary files. Run it as:

    python3 -B site/list-compare-checks.py --core
    python3 -B site/list-compare-checks.py --static
    python3 -B site/list-compare-checks.py --browser
    python3 -B site/list-compare-checks.py --public
    python3 -B site/list-compare-checks.py --all      (core + static, no network)

Modes:
  --core    Extract the production JavaScript from the real HTML file and run it
            against the pre-declared fixtures, using an in-process JavaScript
            engine (JavaScriptCore via ctypes). Both production comparison paths
            (compareLists and compareListsFallback) are exercised against every
            case. Exit 0 only if every case passes on both paths.
  --static  Run the static page gates on both HTML files (tool page + entry
            page). Each gate prints its own result. Exit 0 only if every gate
            passes.
  --browser Run the real WebKit engine (legacy WebView via the Objective-C
            runtime through ctypes, main-thread run loop) against the actual
            page startup in #app-root, including the failure scenarios B0-B5
            and DOM regression flows. This is a real browser DOM, not a
            JavaScript shim. If the environment cannot establish a real
            browser it prints BROWSER UNAVAILABLE and exits 2 - it never fakes
            a pass. Exit 0 only if every browser scenario passes.
  --public  Issue exactly one GET per stable public URL, compare the returned
            bodies with the local files in memory (byte counts, SHA-256,
            containment, release marker, byte equality). No retry, no cache
            busting, no saved copy. Containment is reported as
            PUBLIC CONTAINMENT PASS; byte equality is reported separately and
            is required for the strict g-07 publication claim. Exit 0 only if
            containment holds for both pages.
  --all     --core followed by --static. Never touches the network.

The expected values used by --core are the fixed literal values declared in the
page's acceptance-fixtures JSON (they were written before the implementation),
and the R1 case is additionally cross-checked here against the pre-declared
literal values below. Nothing is generated by the production functions being
tested.
"""

