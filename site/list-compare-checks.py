FORBIDDEN_SCRIPT_TOKENS = [
    ("network: fetch(", "fetch("),
    ("network: XMLHttpRequest", "XMLHttpRequest"),
    ("network: WebSocket", "WebSocket"),
    ("network: EventSource", "EventSource"),
    ("network: sendBeacon", "sendBeacon"),
    ("network: importScripts", "importScripts"),
    ("storage: localStorage", "localStorage"),
    ("storage: sessionStorage", "sessionStorage"),
    ("storage: document.cookie", "document.cookie"),
    ("storage: IndexedDB", "indexedDB"),
    ("storage: openDatabase", "openDatabase"),
    ("storage: caches.", "caches."),
    ("storage: serviceWorker", "serviceWorker"),
    ("clipboard read: readText", "readText"),
    ("clipboard read: clipboard.read", "clipboard.read"),
    ("dynamic markup: innerHTML", "innerHTML"),
    ("dynamic markup: outerHTML", "outerHTML"),
    ("dynamic markup: insertAdjacentHTML", "insertAdjacentHTML"),
    ("dynamic markup: document.write", "document.write"),
    ("dynamic markup: eval(", "eval("),
    ("dynamic markup: new Function(", "new Function("),
    ("dynamic markup: setTimeout(string)", "setTimeout("),
    ("dynamic markup: setInterval(string)", "setInterval("),
    ("url params: location.", "location."),
    ("url params: URLSearchParams", "URLSearchParams"),
    ("url params: document.URL", "document.URL"),
    ("navigation: window.open", "window.open"),
    ("navigation: meta/script redirect tokens", "location="),
    ("share popup: navigator.share", "navigator.share"),
    ("module loading: import(", "import("),
    ("module loading: require(", "require("),
]

CJK_RE = re.compile(r"[\u3000\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff\uff00-\uffef]")


def run_static(html_text):
    parser = parse_page(html_text)
    results = []

    def gate(name, ok, detail):
        results.append((name, ok, detail))
        print("%s - %s (%s)" % ("PASS" if ok else "FAIL", name, detail))

    gate("doctype-html-lang",
         "doctype html" in parser.decl.lower() and any(
             a.get("lang") == "en" for a in parser.attrs_of("html")),
         "decl=%r lang=%r" % (parser.decl, [a.get("lang") for a in parser.attrs_of("html")]))

    charsets = [a.get("charset") for a in parser.attrs_of("meta") if a.get("charset")]
    gate("meta-charset", [c.lower() for c in charsets] == ["utf-8"], "charset=%r" % charsets)

    viewports = [a.get("content") for a in parser.attrs_of("meta")
                 if (a.get("name") or "").lower() == "viewport"]
    gate("meta-viewport", len(viewports) == 1 and "width=device-width" in viewports[0],
         "viewport=%r" % viewports)

    links = parser.attrs_of("link")
    stylesheets = [a for a in links if (a.get("rel") or "").lower() == "stylesheet"]
    gate("single-root-stylesheet",
         [a.get("href") for a in stylesheets] == ["/s.css"] and len(links) == 1,
         "link tags=%r" % links)

    srcs = [a.get("src") for _attrs, a in [((None), d) for d in parser.attrs_of("script")]]
    scripts_with_src = [a for a in parser.attrs_of("script") if a.get("src")]
    gate("scripts-inline-no-src", not scripts_with_src,
         "script src attrs=%r" % [a.get("src") for a in scripts_with_src])

    media_tags = []
    for tag in ("img", "iframe", "video", "audio", "source", "embed", "object", "frame"):
        found = parser.attrs_of(tag)
        if found:
            media_tags.append((tag, found))
    gate("no-other-subresource-tags", not media_tags, "found=%r" % media_tags)

    css_text = "\n".join(parser.styles) + "\n" + "\n".join(
        a.get("style", "") for _t, at in parser.tags for a in [dict(at)])
    css_bad = []
    for token in ("url(", "@import"):
        if token in css_text:
            css_bad.append(token)
    gate("css-no-url-no-import", not css_bad, "offending tokens=%r" % css_bad)

    hrefs = [a.get("href") for a in parser.attrs_of("a")]
    href_ok = True
    href_detail = []
    for h in hrefs:
        if h is None:
            href_ok = False
            href_detail.append("href without value")
            continue
        if "?" in h:
            href_ok = False
            href_detail.append("query string in %r" % h)
        if h.startswith("#"):
            continue
        if not (h.startswith("/zone001/") and h.endswith(".html")):
            href_ok = False
            href_detail.append("not an /zone001/*.html path: %r" % h)
    gate("internal-links-clean", href_ok, "hrefs=%r issues=%r" % (hrefs, href_detail))

    forms = parser.attrs_of("form")
    metas = parser.attrs_of("meta")
    refresh = [a for a in metas if (a.get("http-equiv") or "").lower() == "refresh"]
    gate("no-forms-no-meta-refresh", not forms and not refresh,
         "forms=%d refresh=%d" % (len(forms), len(refresh)))

    script_text = parser.script_text()
    offenders = []
    for label, token in FORBIDDEN_SCRIPT_TOKENS:
        if token in script_text:
            offenders.append(label)
    gate("no-network-storage-clipboard-read-dynamic-markup", not offenders,
         "offending tokens=%r" % offenders)

    visible_text = "".join(parser.visible)
    cjk_found = sorted(set(CJK_RE.findall(visible_text)))
    gate("visible-labels-english-only", not cjk_found, "cjk chars in visible text=%r" % cjk_found)

    bodies = parser.attrs_of("body")
    product_ok = any(b.get("data-product") == PRODUCT_MARKER for b in bodies)
    release_ok = any(b.get("data-release") == RELEASE_MARKER for b in bodies)
    gate("release-markers-present", product_ok and release_ok,
         "data-product=%r data-release=%r" % (
             [b.get("data-product") for b in bodies], [b.get("data-release") for b in bodies]))

    ok_all = all(ok for _n, ok, _d in results)
    print("STATIC %s" % ("PASS" if ok_all else "FAIL"))
    return 0 if ok_all else 1


