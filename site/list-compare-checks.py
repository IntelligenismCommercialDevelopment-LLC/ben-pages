def main(argv):
    modes = [a for a in argv[1:] if a.startswith("--")]
    if len(modes) != 1 or modes[0] not in ("--core", "--static", "--browser", "--public", "--all"):
        print("usage: python3 -B list-compare-checks.py --core|--static|--browser|--public|--all")
        return 2
    mode = modes[0]
    if mode == "--public":
        return run_public()

    html_text = read_page_text(PAGE_REL)
    if mode == "--core":
        return run_core(html_text)
    if mode == "--static":
        return run_static(html_text, read_page_text(INDEX_REL))
    if mode == "--browser":
        return run_browser_entry(html_text)
    rc = run_core(html_text)
    rc2 = run_static(html_text, read_page_text(INDEX_REL))
    return rc if rc != 0 else rc2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
