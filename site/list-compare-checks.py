#!/usr/bin/env python3
"""list-compare-checks.py - independent re-check tool for the list-compare page.

This program is read-only: every mode writes only to stdout / stderr. It never
writes report files, caches, downloaded bodies or temporary files. Run it as:

    python3 -B site/list-compare-checks.py --core
    python3 -B site/list-compare-checks.py --static
    python3 -B site/list-compare-checks.py --public
    python3 -B site/list-compare-checks.py --all      (core + static, no network)

Modes:
  --core    Extract the production JavaScript from the real HTML file and run it
            against the pre-declared fixtures, using an in-process JavaScript
            engine (JavaScriptCore via ctypes). Exit 0 only if every case passes.
  --static  Run the static page gates on the real HTML file. Each gate prints its
            own result. Exit 0 only if every gate passes.
  --public  Issue exactly one GET for the stable tool URL, compare the returned
            body with the local file in memory (byte counts, SHA-256, equality,
            containment, release marker). No retry, no cache busting, no saved copy.
            Exit 0 only if the body was fetched, contains the local bytes and the
            release marker (byte equality is reported, not required for exit 0).
  --all     --core followed by --static. Never touches the network.

The expected values used by --core are the fixed literal values declared in the
page's acceptance-fixtures JSON. They are never generated by the production
functions being tested.
"""

import ctypes
import ctypes.util
import hashlib
import json
import re
import sys
import urllib.request

PAGE_REL = "site/list-compare.html"
PUBLIC_URL = "https://intelligenism.com/zone001/list-compare.html"
RELEASE_MARKER = "lc-20261018-final-lists-1"
PRODUCT_MARKER = "list-compare-v2-final-lists"
WANTED_SCRIPT_IDS = ("acceptance-fixtures", "compare-core", "acceptance-tests")
REQUIRED_CASE_IDS = (
    ["F%d" % i for i in range(1, 12)]
    + ["N%d" % i for i in range(1, 9)]
    + ["T1", "T2"]
)


def page_path():
    import os
    return os.path.join(os.path.dirname(os.path.abspath(__file__)), os.pardir, PAGE_REL)


# --------------------------------------------------------------------------
# HTML extraction
# --------------------------------------------------------------------------

class PageParser(object):
    """Minimal HTML fact extractor. Also grabs inline script bodies by id."""

    def __init__(self):
        from html.parser import HTMLParser
        self._p = HTMLParser(convert_charrefs=True)
        self._p.handle_decl = self.handle_decl
        self._p.handle_starttag = self.handle_starttag
        self._p.handle_endtag = self.handle_endtag
        self._p.handle_data = self.handle_data
        self.decl = ""
        self.tags = []            # (tag, [(attr, value), ...])
        self.scripts = []         # (attrs, text)
        self.styles = []          # text of <style> blocks
        self.visible = []         # text outside script/style
        self._in_script = None
        self._in_style = False

    def handle_decl(self, decl):
        self.decl = decl

    def handle_starttag(self, tag, attrs):
        self.tags.append((tag, attrs))
        if tag == "script":
            self._in_script = (dict(attrs), [])
        elif tag == "style":
            self._in_style = True

    def handle_endtag(self, tag):
        if tag == "script" and self._in_script is not None:
            attrs, chunks = self._in_script
            self.scripts.append((attrs, "".join(chunks)))
            self._in_script = None
        elif tag == "style":
            self._in_style = False

    def handle_data(self, data):
        if self._in_script is not None:
            self._in_script[1].append(data)
        elif self._in_style:
            self.styles.append(data)
        else:
            self.visible.append(data)

    def feed(self, text):
        self._p.feed(text)
        self._p.close()

    def attrs_of(self, tagname):
        out = []
        for tag, attrs in self.tags:
            if tag == tagname:
                out.append(dict(attrs))
        return out

    def script_text(self):
        return "\n".join(text for _attrs, text in self.scripts)


def parse_page(html_text):
    parser = PageParser()
    parser.feed(html_text)
    return parser


# --------------------------------------------------------------------------
# In-process JavaScript engine (JavaScriptCore via ctypes)
# --------------------------------------------------------------------------

class JSRuntimeError(RuntimeError):
    pass


class JSContext(object):
    def __init__(self):
        path = ctypes.util.find_library("JavaScriptCore")
        if not path:
            raise JSRuntimeError("CORE_RUNTIME_UNAVAILABLE: no JavaScriptCore library found")
        try:
            lib = ctypes.CDLL(path)
        except OSError as exc:
            raise JSRuntimeError("CORE_RUNTIME_UNAVAILABLE: cannot load JavaScriptCore: %s" % exc)
        self.lib = lib
        L = lib
        L.JSGlobalContextCreate.restype = ctypes.c_void_p
        L.JSGlobalContextCreate.argtypes = [ctypes.c_void_p]
        L.JSGlobalContextRelease.restype = None
        L.JSGlobalContextRelease.argtypes = [ctypes.c_void_p]
        L.JSStringCreateWithUTF8CString.restype = ctypes.c_void_p
        L.JSStringCreateWithUTF8CString.argtypes = [ctypes.c_char_p]
        L.JSStringRelease.restype = None
        L.JSStringRelease.argtypes = [ctypes.c_void_p]
        L.JSEvaluateScript.restype = ctypes.c_void_p
        L.JSEvaluateScript.argtypes = [
            ctypes.c_void_p, ctypes.c_void_p, ctypes.c_void_p, ctypes.c_void_p,
            ctypes.c_int, ctypes.POINTER(ctypes.c_void_p),
        ]
        L.JSValueToStringCopy.restype = ctypes.c_void_p
        L.JSValueToStringCopy.argtypes = [
            ctypes.c_void_p, ctypes.c_void_p, ctypes.POINTER(ctypes.c_void_p),
        ]
        L.JSStringGetMaximumUTF8CStringSize.restype = ctypes.c_size_t
        L.JSStringGetMaximumUTF8CStringSize.argtypes = [ctypes.c_void_p]
        L.JSStringGetUTF8CString.restype = ctypes.c_size_t
        L.JSStringGetUTF8CString.argtypes = [ctypes.c_void_p, ctypes.c_char_p, ctypes.c_size_t]
        self.ctx = L.JSGlobalContextCreate(None)
        if not self.ctx:
            raise JSRuntimeError("CORE_RUNTIME_UNAVAILABLE: JSGlobalContextCreate returned null")
        self.closed = False

    def close(self):
        if not self.closed and self.ctx:
            self.lib.JSGlobalContextRelease(self.ctx)
            self.closed = True

    def _string_to_python(self, jsstring):
        if not jsstring:
            return ""
        try:
            size = self.lib.JSStringGetMaximumUTF8CStringSize(jsstring)
            buf = ctypes.create_string_buffer(size if size > 0 else 1)
            self.lib.JSStringGetUTF8CString(jsstring, buf, size if size > 0 else 1)
            return buf.value.decode("utf-8", "replace")
        finally:
            self.lib.JSStringRelease(jsstring)

    def eval(self, code, label="script"):
        exc = ctypes.c_void_p()
        s = self.lib.JSStringCreateWithUTF8CString(code.encode("utf-8"))
        if not s:
            raise JSRuntimeError("JSStringCreateWithUTF8CString failed for %s" % label)
        try:
            value = self.lib.JSEvaluateScript(self.ctx, s, None, None, 0, ctypes.byref(exc))
            if exc.value:
                msg = self._string_to_python(
                    self.lib.JSValueToStringCopy(self.ctx, exc, None))
                raise JSRuntimeError("JavaScript exception in %s: %s" % (label, msg))
            if not value:
                raise JSRuntimeError("JavaScript returned no value from %s" % label)
            result = self._string_to_python(
                self.lib.JSValueToStringCopy(self.ctx, value, ctypes.byref(exc)))
            if exc.value:
                msg = self._string_to_python(
                    self.lib.JSValueToStringCopy(self.ctx, exc, None))
                raise JSRuntimeError("JavaScript exception while converting result of %s: %s" % (label, msg))
            return result
        finally:
            self.lib.JSStringRelease(s)


