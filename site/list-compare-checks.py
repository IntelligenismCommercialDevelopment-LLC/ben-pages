CJK_RE = re.compile(r"[\u3000\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff\uff00-\uffef]")
MD_TABLE_RE = re.compile(r"^\s*\|.*\|\s*$", re.MULTILINE)


def run_static(html_text, index_text):
    results = []

    def gate(name, ok, detail):
        results.append((name, ok, detail))
        print("%s - %s (%s)" % ("PASS" if ok else "FAIL", name, detail))

    for label, text in (("tool", html_text), ("entry", index_text)):
        parser = parse_page(text)

        gate("doctype-html-lang:%s" % label,
             "doctype html" in parser.decl.lower() and any(
                 a.get("lang") == "en" for a in parser.attrs_of("html")),
             "decl=%r lang=%r" % (parser.decl, [a.get("lang") for a in parser.attrs_of("html")]))

        charsets = [a.get("charset") for a in parser.attrs_of("meta") if a.get("charset")]
        gate("meta-charset:%s" % label, [c.lower() for c in charsets] == ["utf-8"],
             "charset=%r" % charsets)

        viewports = [a.get("content") for a in parser.attrs_of("meta")
                     if (a.get("name") or "").lower() == "viewport"]
        gate("meta-viewport:%s" % label,
             len(viewports) == 1 and "width=device-width" in viewports[0],
             "viewport=%r" % viewports)

        links = parser.attrs_of("link")
        stylesheets = [a for a in links if (a.get("rel") or "").lower() == "stylesheet"]
        gate("single-root-stylesheet:%s" % label,
             [a.get("href") for a in stylesheets] == ["/s.css"] and len(links) == 1,
             "link tags=%r" % links)

        scripts_with_src = [a for a in parser.attrs_of("script") if a.get("src")]
        gate("scripts-inline-no-src:%s" % label, not scripts_with_src,
             "script src attrs=%r" % [a.get("src") for a in scripts_with_src])

        media_tags = []
        for tag in ("img", "iframe", "video", "audio", "source", "embed", "object", "frame"):
            found = parser.attrs_of(tag)
            if found:
                media_tags.append((tag, found))
        gate("no-other-subresource-tags:%s" % label, not media_tags, "found=%r" % media_tags)

        css_text = "\n".join(parser.styles)
        css_bad = [tok for tok in ("url(", "@import") if tok in css_text]
        gate("css-no-url-no-import:%s" % label, not css_bad, "offending tokens=%r" % css_bad)

        hrefs = [a.get("href") for a in parser.attrs_of("a")]
        href_ok = True
        href_detail = []
        for h in hrefs:
            if h is None:
                href_ok = False
                href_detail.append("href without value")
                continue
            if "?" in h or "#" in h:
                href_ok = False
                href_detail.append("query or fragment in %r" % h)
                continue
            if not (h.startswith("/zone001/") and h.endswith(".html")):
                href_ok = False
                href_detail.append("not an /zone001/*.html path: %r" % h)
        gate("internal-links-clean:%s" % label, href_ok, "hrefs=%r issues=%r" % (hrefs, href_detail))

        forms = parser.attrs_of("form")
        metas = parser.attrs_of("meta")
        refresh = [a for a in metas if (a.get("http-equiv") or "").lower() == "refresh"]
        gate("no-forms-no-meta-refresh:%s" % label, not forms and not refresh,
             "forms=%d refresh=%d" % (len(forms), len(refresh)))

        script_text = parser.script_text()
        offenders = [lbl for lbl, tok in FORBIDDEN_SCRIPT_TOKENS if tok in script_text]
        gate("no-network-storage-clipboard-read-dynamic-markup:%s" % label, not offenders,
             "offending tokens=%r" % offenders)

        visible_text = "".join(parser.visible)
        cjk_found = sorted(set(CJK_RE.findall(visible_text)))
        gate("visible-labels-english-only:%s" % label, not cjk_found,
             "cjk chars in visible text=%r" % cjk_found)

        bodies = parser.attrs_of("body")
        release_ok = any(b.get("data-release") == RELEASE_MARKER for b in bodies)
        gate("release-marker:%s" % label, release_ok,
             "data-release=%r want=%r" % ([b.get("data-release") for b in bodies], RELEASE_MARKER))

        md_tables = MD_TABLE_RE.findall(text)
        gate("no-markdown-table:%s" % label, not md_tables,
             "markdown-table-looking lines=%d" % len(md_tables))

    # tool page specific gates
    tparser = parse_page(html_text)
    tbodies = tparser.attrs_of("body")
    gate("product-marker:tool",
         any(b.get("data-product") == PRODUCT_MARKER for b in tbodies),
         "data-product=%r" % [b.get("data-product") for b in tbodies])

    gate("no-gate-structure:tool",
         not any(tok in html_text for _lbl, tok in GATE_STRUCTURE_TOKENS),
         "offending tokens=%r" % [lbl for lbl, tok in GATE_STRUCTURE_TOKENS if tok in html_text])

    core_src = tparser.script_by_id("compare-core") or ""
    ui_src = tparser.script_by_id("compare-ui") or ""
    tests_src = tparser.script_by_id("acceptance-tests") or ""
    start_src = tparser.script_by_id("page-start") or ""
    diag_src = tparser.script_by_id("diagnostics") or ""

    gate("fallback-path-present:tool",
         "function compareListsFallback" in core_src
         and "compareListsFallback(els.leftInput.value" in ui_src
         and "catch (primaryError)" in ui_src,
         "fallback defined=%s called in doCompare=%s primary catch=%s" % (
             "function compareListsFallback" in core_src,
             "compareListsFallback(els.leftInput.value" in ui_src,
             "catch (primaryError)" in ui_src))

    gate("workspace-start-independent:tool",
         "createComparisonApp" in start_src
         and "acceptance-fixtures" not in start_src
         and "acceptance-fixtures" not in ui_src
         and "fixtureById" not in ui_src,
         "start calls createComparisonApp=%s start reads fixtures=%s ui reads fixtures=%s" % (
             "createComparisonApp" in start_src,
             "acceptance-fixtures" in start_src,
             "acceptance-fixtures" in ui_src or "fixtureById" in ui_src))

    diag_ids = set(re.findall(r"getElementById\('([^']+)'\)", diag_src))
    allowed_diag_ids = set(['diagnostic-status', 'core-report', 'dom-report', 'acceptance-fixtures'])
    gate("diagnostics-cannot-touch-workspace:tool",
         "app-root" not in diag_src
         and "setControlsEnabled" not in diag_src
         and diag_ids <= allowed_diag_ids,
         "diag touches app-root=%s setControlsEnabled=%s dom ids=%r" % (
             "app-root" in diag_src, "setControlsEnabled" in diag_src, sorted(diag_ids)))

    gate("diagnostics-run-on-click-only:tool",
         "runDiagnostics" in diag_src
         and "addEventListener('click', runDiagnostics)" in start_src
         and "runDiagnostics();" not in html_text.replace("runDiagnostics();", "", 0),
         "runDiagnostics defined=%s bound to click=%s" % (
             "runDiagnostics" in diag_src,
             "addEventListener('click', runDiagnostics)" in start_src))

    gate("both-paths-tested-in-runner:tool",
         "compareListsFallback" in tests_src and "runOneCaseOnPath" in tests_src,
         "runner names fallback=%s per-path runner=%s" % (
             "compareListsFallback" in tests_src, "runOneCaseOnPath" in tests_src))

    gate("d8-observes-textarea-value:tool",
         "finalText(root, 'final-common').indexOf" in diag_src,
         "D8 literal marker checked on textarea.value")

    # fixture coverage + pre-declared R1 values
    fixtures_src = tparser.script_by_id("acceptance-fixtures") or ""
    try:
        fixtures_obj = json.loads(fixtures_src)
        cases = fixtures_obj["cases"] if isinstance(fixtures_obj, dict) else fixtures_obj
        by_id = dict((c.get("id"), c) for c in cases)
        missing = [cid for cid in REQUIRED_CASE_IDS if cid not in by_id]
        gate("fixture-coverage:tool", not missing, "missing=%r total=%d" % (missing, len(cases)))
        r1 = by_id.get("R1") or {}
        r1_expected = r1.get("expected") or {}
        r1_ok = (
            r1.get("left") == R1_PREDECLARED["left"]
            and r1.get("right") == R1_PREDECLARED["right"]
            and r1.get("options") == R1_PREDECLARED["options"]
            and r1_expected.get("leftStats") == R1_PREDECLARED["leftStats"]
            and r1_expected.get("rightStats") == R1_PREDECLARED["rightStats"]
            and r1_expected.get("final") == R1_PREDECLARED["final"]
        )
        gate("r1-predeclared-values:tool", r1_ok,
             "R1 fixture equals the pre-declared plan values=%s" % r1_ok)
    except ValueError as exc:
        gate("fixture-coverage:tool", False, "fixtures JSON unreadable: %s" % exc)
        gate("r1-predeclared-values:tool", False, "fixtures JSON unreadable")

    # entry page specific gates
    iparser = parse_page(index_text)
