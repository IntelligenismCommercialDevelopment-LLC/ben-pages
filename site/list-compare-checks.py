class Objc(object):
    def __init__(self):
        for name in ("AppKit", "WebKit"):
            lib = ctypes.util.find_library(name)
            if not lib:
                raise BrowserUnavailable("BROWSER UNAVAILABLE: framework %s not found" % name)
            ctypes.CDLL(lib)
        objc_lib = ctypes.util.find_library("objc")
        if not objc_lib:
            raise BrowserUnavailable("BROWSER UNAVAILABLE: libobjc not found")
        self.objc = ctypes.CDLL(objc_lib)
        self.objc.objc_getClass.restype = ctypes.c_void_p
        self.objc.objc_getClass.argtypes = [ctypes.c_char_p]
        self.objc.sel_registerName.restype = ctypes.c_void_p
        self.objc.sel_registerName.argtypes = [ctypes.c_char_p]
        self.msg = self.objc.objc_msgSend

    def cls(self, name):
        c = self.objc.objc_getClass(name.encode("utf-8"))
        if not c:
            raise BrowserUnavailable("BROWSER UNAVAILABLE: Objective-C class %s missing" % name)
        return c

    def sel(self, name):
        return self.objc.sel_registerName(name.encode("utf-8"))

    def send(self, restype, target, selname, *args, **kwargs):
        argtypes = kwargs.get("argtypes", [])
        self.msg.restype = restype
        self.msg.argtypes = [ctypes.c_void_p, ctypes.c_void_p] + list(argtypes)
        return self.msg(target, self.sel(selname), *args)


