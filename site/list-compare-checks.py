def clip(v, n=300):
    s = v if isinstance(v, str) else json.dumps(v, ensure_ascii=False)
    return s if len(s) <= n else s[:n] + "...[clipped]"


def run_core(html_text):
    parser = parse_page(html_text)
    scripts = {}
    for attrs, text in parser.scripts:
        sid = attrs.get("id")
        if sid in WANTED_SCRIPT_IDS:
            scripts[sid] = text
    for sid in WANTED_SCRIPT_IDS:
        if sid not in scripts:
            print("FAIL - script block #%s missing from the page" % sid)
            return 1

    fixtures_src = scripts["acceptance-fixtures"]
    try:
        fixtures_obj = json.loads(fixtures_src)
    except ValueError as exc:
        print("FAIL - acceptance-fixtures is not valid JSON: %s" % exc)
        return 1
    cases = fixtures_obj["cases"] if isinstance(fixtures_obj, dict) else fixtures_obj
    case_ids = [c.get("id") for c in cases]

    driver = (
        "(function () {\n"
        "  var fixtures = JSON.parse(%s);\n"
        "  var report = runAcceptanceTests(fixtures);\n"
        "  return JSON.stringify(report);\n"
        "})()"
        % json.dumps(fixtures_src)
    )
    code = scripts["compare-core"] + "\n;\n" + scripts["acceptance-tests"] + "\n;\n" + driver

    try:
        ctx = JSContext()
    except JSRuntimeError as exc:
        print(str(exc))
        return 1
    try:
        raw = ctx.eval(code, "acceptance run")
    except JSRuntimeError as exc:
        print("FAIL - %s" % exc)
        ctx.close()
        return 1
    ctx.close()

    try:
        report = json.loads(raw)
    except ValueError as exc:
        print("FAIL - runner returned invalid JSON: %s" % exc)
        return 1

    problems = []
    missing = [cid for cid in REQUIRED_CASE_IDS if cid not in case_ids]
    if missing:
        problems.append("fixture coverage incomplete, missing case ids: %s" % ", ".join(missing))
    total = len(report.get("cases", []))
    if total == 0:
        problems.append("runner reported zero cases; an empty report is not a pass")

    passed = 0
    for case in report.get("cases", []):
        ok = bool(case.get("pass"))
        if ok:
            passed += 1
        print("CASE %s pass=%s" % (case.get("id"), "true" if ok else "false"))
        print("  expected: %s" % clip(case.get("expected")))
        print("  actual:   %s" % clip(case.get("actual")))
        assertions = case.get("assertions", [])
        saw_primary = False
        saw_fallback = False
        for a in assertions:
            name = str(a.get("name"))
            if name.startswith("[primary(compareLists)]"):
                saw_primary = True
            if name.startswith("[fallback(compareListsFallback)]"):
                saw_fallback = True
            aok = bool(a.get("pass"))
            if not aok:
                print("  ASSERT pass=false %s" % name)
                print("    expected: %s" % clip(a.get("expected")))
                print("    actual:   %s" % clip(a.get("actual")))
        if not saw_primary or not saw_fallback:
            problems.append("case %s did not exercise both production paths (primary=%s fallback=%s)"
                            % (case.get("id"), saw_primary, saw_fallback))
        acount = len(assertions)
        afail = sum(1 for a in assertions if not a.get("pass"))
        print("  assertions: %d, failed: %d" % (acount, afail))
        if acount == 0:
            problems.append("case %s ran no assertions" % case.get("id"))
    failed = total - passed
    print("TOTAL cases=%d pass=%d fail=%d" % (total, passed, failed))
    for p in problems:
        print("FAIL - %s" % p)
    ok_all = report.get("passed") is True and failed == 0 and not problems and total > 0
    print("CORE %s" % ("PASS" if ok_all else "FAIL"))
    return 0 if ok_all else 1


